// A small reusable host entry. Empty lookups, the single image continuation and
// file transfers remain inside this program; no model API or copied credentials.
(() => {
  const fail=code=>{throw Object.assign(new Error(code),{code});};
  const quote=v=>"'"+v.replaceAll("'","''")+"'";
  function utf8Bytes(s){let n=0;for(const c of s){const k=c.codePointAt(0);n+=k<128?1:k<2048?2:k<65536?3:4;}return n;}
  function json(raw){if(raw?.isError)fail('LOCAL_ATTACHMENT_IO_FAILED');try{return JSON.parse(raw.content.filter(c=>c.type==='text').map(c=>c.text).join('\n'));}catch{fail('LOCAL_ATTACHMENT_IO_NOT_JSON');}}
  const instructions='在已允许的协作范围内发送必要材料并取回结果。调用 Codex 将正文控制为目标、必要背景、交付要求和附件引用；长方案、代码或日志用 attachments，directMaterials 仅放必要短片段，用户无需手工拆分。任务版本、提交协议和哈希由程序处理。空查询、分块和五分钟兜底在同一程序内，不逐次返回模型。多目标使用 runMany，不同 Chat 并行，同一 Chat 不插入新任务。超时用原 packetPath 续等，不重发回执不明的消息。生图只逐条发送，用户自行下载。';
  function describe(){return {name:'codex_chat_transport',host:'Codex desktop tool bridge',standaloneMcp:false,instructions,
    methods:{run:{required:['scriptRoot','outputRoot','requestPath OR packetPath','deliveryAuthorized'],request:'goal, optional targetThreadId, directMaterials, attachments, receiveAttachments; imageGeneration/imagePrompt(s) for send-only images'},
      runMany:{required:['scriptRoot','jobs','deliveryAuthorized'],jobs:'1–8 objects with requestPath OR packetPath and distinct outputRoot; each packet uses a registered target in the same current account and Codex thread',result:'one outcome or recoverable error per job; independent Chat jobs wait concurrently'}},
    setup:'Resolve the Chat by its desktop conversation name; prepare.mjs target-bind <exact Chat URL> [authorized root] [title]. Internal IDs and JSON are generated by Codex, not the user.',
    limitations:'Requires injected host tools; remote MCP tools do not inherit desktop messaging or account identity. No idle event wakeup. Host continuations may still use model inference.'};}
  function requireBridge(tools){
    if(!tools||['exec_command','apply_patch','mcp__codex_app__read_thread','mcp__codex_app__send_message_to_thread','mcp__codex_apps__sites_get_site'].some(name=>typeof tools[name]!=='function'))fail('HOST_BRIDGE_REQUIRED');
  }
  async function command(tools,args,max=2000){
    const r=await tools.exec_command({cmd:'& '+args.map(quote).join(' '),max_output_tokens:max});
    if(r.exit_code!==0||r.session_id)fail(/^[A-Z][A-Z0-9_]+$/.test(r.output?.trim()??'')?r.output.trim():'LOCAL_PREPARATION_FAILED');
    return r.output;
  }
  function paths(options){
    const {scriptRoot,requestPath,packetPath,outputRoot,nodePath='C:/Program Files/nodejs/node.exe'}=options??{};
    for(const p of [scriptRoot,outputRoot,nodePath,requestPath??packetPath])if(typeof p!=='string'||!p||/[\r\n\0]/.test(p))fail('ENTRY_PATH_REQUIRED');
    if(!!requestPath===!!packetPath)fail('ONE_REQUEST_OR_PACKET_REQUIRED');
    return {scriptRoot,requestPath,packetPath,outputRoot,nodePath,preparePath:scriptRoot.replaceAll('\\','/')+'/prepare.mjs'};
  }
  async function run(tools,inventory,options){
    requireBridge(tools);
    const {scriptRoot,requestPath,packetPath,outputRoot,nodePath,preparePath}=paths(options);
    const started=Date.now(),calls={};
    const measured=new Proxy(tools,{get(target,name){const fn=target[name];if(typeof fn!=='function')return fn;return async(...args)=>{calls[name]=(calls[name]??0)+1;return await fn(...args);};}});
    let selected=packetPath;
    if(requestPath)selected=JSON.parse(await command(measured,[nodePath,preparePath,'prepare',requestPath])).packetPath;
    const job=JSON.parse(await command(measured,[nodePath,preparePath,'load',selected],30000));
    const imageSendOnly=job.packet.imageDelivery==='manual';
    if(job.packet.imageGeneration&&!imageSendOnly)fail('LEGACY_IMAGE_RETURN_DISABLED');
    async function readModule(name){
      const r=await measured.exec_command({cmd:'Get-Content -LiteralPath '+quote(scriptRoot+'/'+name)+' -Raw',max_output_tokens:22000});
      if(r.exit_code!==0||r.session_id)fail('ENTRY_MODULE_READ_FAILED');return new Function('return (\n'+r.output+'\n)')();
    }
    const api=await readModule('host-runtime.js'),attachment=job.packet.attachments?await readModule('attachment-host-runtime.js'):null;
    const uri='file:///'+encodeURI((scriptRoot+'/attachment-local.mjs').replaceAll('\\','/')).replaceAll('#','%23').replaceAll('?','%3F');
    if(attachment){if(typeof measured.mcp__node_repl__js!=='function')fail('LOCAL_ATTACHMENT_BRIDGE_REQUIRED');const init=await measured.mcp__node_repl__js({code:'var collaborationFiles = await import('+JSON.stringify(uri)+'); var collaborationFS = await import("node:fs/promises"); await collaborationFS.mkdir('+JSON.stringify(outputRoot)+',{recursive:true}); nodeRepl.write({ready:true});',title:'准备任务文件传输'});if(init.isError)fail('LOCAL_ATTACHMENT_IO_FAILED');}
    const io={};
    for(const method of ['describe','readChunk','startDownload','appendChunk','finishDownload','cancelDownload'])io[method]=async(...args)=>{
      const code='nodeRepl.write(JSON.stringify(await collaborationFiles['+JSON.stringify(method)+'](...'+JSON.stringify(args)+')));';
      if(utf8Bytes(code)>64000)fail('LOCAL_FILE_BRIDGE_CODE_LIMIT');
      return json(await measured.mcp__node_repl__js({code,title:'程序传输原文件并核验'}));
    };
    let sent=job.resume?.delivery==='sent',exported=job.resume?.imageExport?.delivery==='sent';
    const checkpoint=async s=>{
      const patch='*** Begin Patch\n*** Add File: '+job.statePath.replaceAll('\\','/')+'\n+'+JSON.stringify(s,null,2).split('\n').join('\n+')+'\n*** End Patch';
      const r=await measured.apply_patch(patch);if(r?.isError)fail('CHECKPOINT_NOT_SAVED');
      if(!sent&&s.delivery==='sent'){sent=true;options.onProgress?.({stage:'sent'});}
      if(!exported&&s.imageExport?.delivery==='sent'){exported=true;options.onProgress?.({stage:'automatic-image-export'});}
    };
    const outcome=await api.delegateAndWait(job.packet,api.bindHost(measured,inventory,job.packet.connection,{imageSendOnly}),{
      deliveryAuthorized:options.deliveryAuthorized,resume:job.resume,timeoutMs:options.timeoutMs,pollIntervalMs:options.pollIntervalMs??30000,
      waitStrategy:options.waitStrategy??(job.packet.imageGeneration?'thread':'result'),completionFallback:options.completionFallback??!job.packet.imageGeneration,
      fallbackIntervalMs:options.fallbackIntervalMs,threadProbeIntervalMs:options.threadProbeIntervalMs,
      execution:api.bindExecution(measured,{nodePath,preparePath,packetPath:selected}),checkpoint,
      ...(attachment?{attachments:{api:attachment,host:attachment.bind(measured,inventory,job.packet.connection?.toolPrefix,job.packet.connection),io,outputRoot}}:{})
    });
    const metrics={startedAt:new Date(started).toISOString(),endedAt:new Date().toISOString(),elapsedMs:Date.now()-started,toolCalls:calls,waitProgramModelAPICalls:0};
    const path=outputRoot.replaceAll('\\','/')+'/outcome.json';
    const saved=await measured.apply_patch('*** Begin Patch\n*** Add File: '+path+'\n+'+JSON.stringify({outcome,metrics},null,2).split('\n').join('\n+')+'\n*** End Patch');
    if(saved?.isError)fail('OUTCOME_NOT_SAVED');
    return {outcome,metrics,recordPath:path,packetPath:selected};
  }
  async function runMany(tools,inventory,options){
    requireBridge(tools);
    const {jobs,...common}=options??{};
    if(!Array.isArray(jobs)||jobs.length<1||jobs.length>8)fail('INVALID_BATCH_JOBS');
    if(common.deliveryAuthorized!==true)fail('DELIVERY_AUTHORIZATION_REQUIRED');
    const selected=jobs.map(job=>({...common,...job,deliveryAuthorized:true}));
    for(const o of selected)if(o.scriptRoot!==common.scriptRoot||o.nodePath!==common.nodePath)fail('BATCH_ENTRY_MISMATCH');
    const roots=selected.map(o=>paths(o).outputRoot.replaceAll('\\','/').replace(/\/+$/,'').toLowerCase());
    if(roots.some(p=>p.split('/').some(s=>s==='.'||s==='..'))||roots.some((p,i)=>roots.some((q,j)=>i!==j&&(p===q||p.startsWith(q+'/')))))fail('BATCH_OUTPUTS_MUST_BE_SEPARATE');
    const started=Date.now(),calls={};let localBridge=Promise.resolve(),desktopMessage=Promise.resolve();
    const measured=new Proxy(tools,{get(target,name){const fn=target[name];if(typeof fn!=='function')return fn;return async(...args)=>{
      calls[name]=(calls[name]??0)+1;
      if(name==='mcp__codex_app__send_message_to_thread'){
        const next=desktopMessage.then(()=>fn(...args));desktopMessage=next.catch(()=>{});return await next;
      }
      if(name!=='mcp__node_repl__js')return await fn(...args);
      const next=localBridge.then(()=>fn(...args));localBridge=next.catch(()=>{});return await next;
    };}});
    // Finish local preparation and scope checks for every item before any send.
    const ready=[];let source,account;const targets=new Set(),tasks=new Set();
    for(const o of selected){
      const p=paths(o);let selectedPacket=p.packetPath;
      if(p.requestPath)selectedPacket=JSON.parse(await command(measured,[p.nodePath,p.preparePath,'prepare',p.requestPath])).packetPath;
      const job=JSON.parse(await command(measured,[p.nodePath,p.preparePath,'load',selectedPacket],30000)),packet=job.packet;
      if(packet.source?.routeTarget!==true||!packet.source.codexThreadId||!packet.connection?.accountId)fail('BATCH_REGISTERED_TARGET_REQUIRED');
      if(source&&source!==packet.source.codexThreadId||account&&account!==packet.connection.accountId)fail('BATCH_SCOPE_MISMATCH');
      source=packet.source.codexThreadId;account=packet.connection.accountId;
      if(targets.has(packet.target.threadId))fail('BATCH_CHAT_MUST_BE_DISTINCT');targets.add(packet.target.threadId);
      const task=packet.assignment.taskId+'|'+packet.assignment.revision;
      if(tasks.has(task))fail('BATCH_TASK_MUST_BE_DISTINCT');tasks.add(task);
      ready.push({...o,requestPath:undefined,packetPath:selectedPacket,onProgress:event=>o.onProgress?.({...event,targetThreadId:packet.target.threadId,taskId:packet.assignment.taskId})});
    }
    const settled=await Promise.allSettled(ready.map(o=>run(measured,inventory,o)));
    const reports=settled.map((r,i)=>r.status==='fulfilled'?{...r.value,status:r.value.outcome.status}:
      {status:'failed',errorCode:/^[A-Z][A-Z0-9_]+$/.test(r.reason?.code??r.reason?.message??'')?(r.reason.code??r.reason.message):'ENTRY_EXECUTION_FAILED',packetPath:ready[i].packetPath,outputRoot:ready[i].outputRoot});
    return {status:reports.every(r=>['completed','sent'].includes(r.status))?'completed':'partial',jobs:reports,
      metrics:{startedAt:new Date(started).toISOString(),endedAt:new Date().toISOString(),elapsedMs:Date.now()-started,toolCalls:calls,waitProgramModelAPICalls:0}};
  }
  return {run,runMany,describe,utf8Bytes};
})()
